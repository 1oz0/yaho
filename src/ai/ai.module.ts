/**
 * Claude API 연동 모듈.
 *
 * ── 어디에 쓰는가 ───────────────────────────────────────────────────────────
 *   TransactionsModule  거래 카테고리 분류 (가맹점 단위)
 *   PersonaModule       페르소나 두 축 선정 + 개인화 문구
 *   TravelModule        페르소나 맞춤 여행코스 생성
 *
 * ── 어디에 안 쓰는가 ────────────────────────────────────────────────────────
 *   금액이 오가는 곳 전부. 절약 목표 배분, 주차별 예산, 진척률, 여행 경비 정산은
 *   모두 산술이다. 모델이 더한 숫자는 검산할 방법이 없고, 화면에 뜬 합계가 안 맞으면
 *   그것대로 서비스가 무너진다.
 *
 * ── 평가기준 ③ 을 어떻게 지키는가 ───────────────────────────────────────────
 * "핵심 계산 로직이 AI 없이 결정론적으로 동작하는가" — 위 세 곳 모두 **AI 실패 시
 * 규칙 기반으로 자동 강등**된다. 키를 지우고 서버를 띄워도 전 화면이 그대로 뜨며,
 * 달라지는 것은 분류 정확도와 문구의 개인화 정도뿐이다. `AI_*_ENABLED=false` 셋으로
 * 완전 오프라인 리허설이 가능하다.
 */
